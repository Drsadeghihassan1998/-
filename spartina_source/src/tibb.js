/* ---------- محاسبه ---------- */
const tibbA = p => p.tibbA || (p.tibbA = { sette: {}, organ: {}, humor: {}, flags: {} });
// off = کنار گذاشته در بازبینی ۱۴۰۵/۰۸ (جای پاسخ‌های قبلی با شماره‌ی ردیف حفظ می‌شود، پس ردیف حذف نمی‌شود)
const forSex = (it, sex) => !it.off && !(it.f && sex !== 'f') && !(it.mOnly && sex !== 'm');
function setteScore(p, sec) {
  const ans = (tibbA(p).sette[sec.k]) || {};
  let sum = 0, n = 0, total = 0;
  sec.items.forEach((it, i) => {
    if (it.h || !forSex(it, p.sex)) return;
    total++;
    const a = ans[i]; if (a == null) return;
    sum += it.pos ? SETTE_VAL[3 - a] : SETTE_VAL[a]; n++;
  });
  const score = n ? sum / (2 * n) * 20 : null;
  return { score, n, total, band: score == null ? '' : SETTE_BAND[Math.min(9, Math.floor(score / 2))] };
}
function organScore(p, org) {
  const ans = (tibbA(p).organ[org.k]) || {};
  const s = { h: { l: 0, r: 0, n: 0 }, w: { l: 0, r: 0, n: 0 } };
  const t = { h: 0, w: 0 }, seen = { h: 0, w: 0 };
  ['h', 'w'].forEach(ax => org[ax].forEach((it, i) => {
    if (!forSex(it, p.sex)) return;
    t[ax]++;
    const a = ans[ax + i]; if (a == null) return;
    seen[ax]++;
    if (a === 'x') return; // «نمی‌دانم»
    s[ax].l += a / 5; s[ax].r += (10 - a) / 5; s[ax].n++;
  }));
  const cls = (x, a, b) => { const t = x.l + x.r; if (!t) return 'mid'; const tol = MIZAJ_TOL * t; return x.l - x.r > tol ? a : x.r - x.l > tol ? b : 'mid'; };
  const pct = x => x.l + x.r ? x.l / (x.l + x.r) * 100 : 50;
  const H = cls(s.h, 'hot', 'cold'), W = cls(s.w, 'wet', 'dry');
  // مثل مزاج جبلی: نتیجه فقط با پاسخ عددی دست‌کم نیمی از سؤال‌های هر محور
  const done = s.h.n >= Math.ceil(MIZAJ_MIN * t.h) && s.w.n >= Math.ceil(MIZAJ_MIN * t.w);
  return { hot: pct(s.h), wet: pct(s.w), nh: seen.h, nw: seen.w, th: t.h, tw: t.w, H, W, key: H + '-' + W, done };
}
const humorItem = it => typeof it === 'string' ? { q: it } : it;
function humorScore(p, hm) {
  const ans = (tibbA(p).humor[hm.k]) || {};
  let sum = 0, n = 0, total = 0;
  hm.items.forEach((x, i) => { const it = humorItem(x); if (!forSex(it, p.sex)) return; total++; const a = ans[i]; if (a == null) return; sum += a; n++; });
  const score = n ? sum / (2 * n) * 20 : null;
  return { score, n, total, band: score == null ? '' : HUMOR_BAND.find(([lim]) => score < lim)[1] };
}
function tibbResult(p) {
  return {
    jebli: mizajOf(p),
    sette: SETTE.map(sec => ({ k: sec.k, t: sec.t, ...setteScore(p, sec) })),
    organs: ORGANS.map(org => ({ k: org.k, t: org.t, ...organScore(p, org) })),
    humors: HUMORS.map(hm => ({ k: hm.k, t: hm.t, s: hm.s, ...humorScore(p, hm) })),
    flags: TIBB_FLAGS.filter(([k]) => tibbA(p).flags[k]).map(([, t]) => t),
  };
}

