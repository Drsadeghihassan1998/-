/* تبدیل وکتور گرافیکی بسته‌بندی به Data URI تصویر برای لود در تگ img */
function makeSuppBrandImageUri(b) {
  const svg = suppBrandSvg(b, 160, 200);
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

/* دریافت تصویر فعال محصول (تصویر سفارشی ذخیره‌شده یا تصویر پیش‌فرض برند) */
function getBrandImg(b) {
  if (!b) return '';
  try {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('spartina_supp_img_' + b.id);
      if (saved) return saved;
    }
  } catch (e) {}
  if (b.image) return b.image;
  return makeSuppBrandImageUri(b);
}

/* ایجاد تگ تصویر استاندارد img برای هر کارت مکمل */
function suppBrandImgTag(b, opts = {}) {
  const cls = opts.cls || 'bc-img';
  const idAttr = opts.id ? ` id="${opts.id}"` : ` id="bc-img-${b.id}"`;
  const src = getBrandImg(b);
  return `<img class="${cls}"${idAttr} src="${src}" alt="${b.nameFa} - ${b.nameEn}" loading="lazy" onerror="handleSuppImgError(this, '${b.id}')" />`;
}

